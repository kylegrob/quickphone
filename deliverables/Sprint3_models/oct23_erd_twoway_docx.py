def cell_text(tc):
    return ''.join(re.findall(r'<w:t(?: [^>]*)?>([^<]*)</w:t>', tc))


def set_cell(tc, text, width):
    tc = re.sub(r'<w:tcW w:type="dxa" w:w="\d+"/>', '<w:tcW w:type="dxa" w:w="%d"/>' % width, tc, count=1)
    ts = list(re.finditer(r'<w:t(?: [^>]*)?>[^<]*</w:t>', tc))
    first = ts[0]
    out = tc[:first.start()] + '<w:t xml:space="preserve">' + esc(text) + '</w:t>'
    rest = tc[first.end():]
    return out + re.sub(r'<w:t(?: [^>]*)?>[^<]*</w:t>', '<w:t xml:space="preserve"></w:t>', rest)


def widen(tbl, table):
    tbl = re.sub(r'<w:tblGrid>.*?</w:tblGrid>', '<w:tblGrid>' + ''.join('<w:gridCol w:w="%d"/>' % w for w in GRID) + '</w:tblGrid>', tbl, flags=re.S)
    used = set()

    def row(m):
        tr = m.group(0)
        tcs = list(re.finditer(r'<w:tc>.*?</w:tc>', tr, re.S))
        assert len(tcs) == 4, (table, len(tcs))
        cells = [re.sub(r'<w:tcW w:type="dxa" w:w="\d+"/>', '<w:tcW w:type="dxa" w:w="%d"/>' % GRID[i], c.group(0), count=1)
                 for i, c in enumerate(tcs)]
        col = cell_text(cells[1]).split(' (')[0].strip()
        if '<w:tblHeader/>' in tr:
            d, v = 'Default', 'Valid values'
        else:
            d, v = V.get((table, col), ('', '')); used.add(col)
        cells += [set_cell(cells[3], d, GRID[4]), set_cell(cells[3], v, GRID[5])]
        return tr[:tcs[0].start()] + ''.join(cells) + tr[tcs[-1].end():]
    tbl = re.sub(r'<w:tr>.*?</w:tr>|<w:tr [^>]*>.*?</w:tr>', row, tbl, flags=re.S)
    missing = {c for (t, c) in V if t == table} - used
    assert not missing, (table, missing)
    return tbl


def main(src, dst):
    z = zipfile.ZipFile(src); d = z.read('word/document.xml').decode('utf-8')
    for old, new in TEXT:
        hits = [m for m in re.finditer(r'<w:p[ >].*?</w:p>', d, re.S) if old in para_text(m.group(0))]
        assert len(hits) == 1, (len(hits), old[:60])
        m = hits[0]; d = d[:m.start()] + replace_in_para(m.group(0), old, new) + d[m.end():]
    a = d.find('Appendix A. Physical data dictionary'); b = d.find('Appendix B. Data flow dictionary')
    head, body, tail = d[:a], d[a:b], d[b:]
    out, pos, n = [], 0, 0
    for m in re.finditer(r'<w:tbl>.*?</w:tbl>', body, re.S):
        title = para_text(re.findall(r'<w:p[ >].*?</w:p>', body[:m.start()], re.S)[-1]).split()[0]
        out.append(body[pos:m.start()]); out.append(widen(m.group(0), title)); pos = m.end(); n += 1
    out.append(body[pos:])
    assert n == 16, n
    d = head + ''.join(out) + tail
    tmp = dst + '.tmp'
    with zipfile.ZipFile(src) as zi, zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as zo:
        for item in zi.infolist():
            zo.writestr(item, d.encode('utf-8') if item.filename == 'word/document.xml' else zi.read(item.filename))
    os.replace(tmp, dst)
    print('ok:', len(TEXT), 'paragraphs,', n, 'tables')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
